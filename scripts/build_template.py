"""Build switch/countersign.template.yaml (Switch template v2) from agents/intake/instructions.md.

The template must carry the agent's instructions inline, so it is generated to avoid drift:
  uv run python scripts/build_template.py          # write the file
  uv run python scripts/build_template.py --check  # exit 1 when the committed file is stale

Run it in Switch Console (see README): it creates the room group, the three rooms, the links
and the Claude `intake` agent. Registered agents (countersign, scripted-intake, rogue) must exist
first (`just setup`). Room documents come from scripts/create_docs.py (not expressible).
Not expressible in documented v2 syntax: the exclusive `preparer` role (P3-T2); layer 1 and
layer 2 do not depend on it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "switch" / "countersign.template.yaml"
CLAUDE_MD = ROOT / "agents" / "intake" / "workspace" / "CLAUDE.md"

ROOMS = {
    "intake": (
        "ap-intake",
        "Drop invoices here and mention @intake. The intake agent can't pay; Countersign decides.",
        ["intake", "scripted-intake", "countersign"],
    ),
    "approvals": (
        "ap-approvals",
        "Approve with `@countersign approve CS-xxxxxx`. Only listed approvers count. "
        "Agents can't approve.",
        ["countersign", "rogue"],
    ),
    "audit": (
        "ap-audit",
        "Hash-chained receipts from Countersign. Verify with `just verify`.",
        ["countersign"],
    ),
}


def build() -> dict[str, object]:
    instructions = (ROOT / "agents" / "intake" / "instructions.md").read_text(encoding="utf-8")
    resources: dict[str, object] = {
        "flow": {
            "type": "group",
            "name": "Countersign AP",
            "description": "Invoices are prepared, approved by named humans, paid and receipted.",
            "links": [
                {"from": "intake", "to": "approvals", "label": "proposals"},
                {"from": "approvals", "to": "audit", "label": "receipts"},
            ],
        },
        "intake_agent": {
            "type": "agent",
            "name": "intake",
            "display_name": "Intake",
            "description": "Reads invoices and proposes payments. Cannot pay or approve.",
            "instructions": instructions,
            "provider": "claude",
            "machine": "{machine}",
            "directory": "{workspace}",
            "auto_mode": True,
            "auto_approve": False,
            "can_manage_agents": False,
            "addressing": {"anyone_in": ["intake"]},
        },
    }
    for key, (name, header, agents) in ROOMS.items():
        resources[key] = {
            "type": "room",
            "name": name,
            "description": header,
            "instructions": header,
            "bridge": "{bridge}",
            "channel_type": "channel_public",
            "group": "flow",
            "agents": ["intake_agent" if a == "intake" else a for a in agents]
            if key == "intake"
            else agents,
            "users": ["{$creator}"],
        }
    return {
        "version": 2,
        "params": {
            "bridge": {"type": "bridge", "default": ["$first"], "description": "Messaging app"},
            "machine": {"type": "machine", "default": ["$first"], "description": "Runs intake"},
            "workspace": {
                "type": "directory",
                "required": True,
                "description": "Absolute path of agents/intake/workspace in this repo",
            },
        },
        "resources": resources,
    }


class _Dumper(yaml.SafeDumper):
    """Write multi-line strings as readable literal blocks."""


def _str(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _str)


def render() -> str:
    header = "# Generated by scripts/build_template.py from agents/intake/instructions.md.\n"
    header += "# Do not edit.\n"
    body = yaml.dump(build(), Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=100)
    return header + body


HEADER = """# Vendor list (generated from switch/vendors.yaml; do not edit)

Use this table for `vendor_id` (match the vendor name on the invoice). The `vendors.yaml` room
document is not available in #ap-intake, so read this file instead. If the invoice's vendor is not
listed, use `V-UNKNOWN`. Compare the invoice's account number with the one below to decide whether
to add a `BANK_CHANGED` flag, and its amount with the baseline for `AMOUNT_ANOMALY` (more than
twice the baseline). Countersign checks all of this itself; your flags are advice.

| vendor_id | name | account on file | routing | baseline (USD) |
|---|---|---|---|---|
"""


def render_claude_md() -> str:
    """The vendor list the intake agent reads (it is not in the room that holds vendors.yaml)."""
    vendors = yaml.safe_load((ROOT / "switch" / "vendors.yaml").read_text(encoding="utf-8"))
    rows = [
        f"| {v['vendor_id']} | {v['name']} | {v['account_number']} | {v['routing_number']} "
        f"| {v['baseline_cents'] / 100:,.2f} |"
        for v in vendors["vendors"]
    ]
    return HEADER + "\n".join(rows) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    text, md = render(), render_claude_md()
    if ap.parse_args().check:
        fresh = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        fresh = fresh and CLAUDE_MD.is_file() and CLAUDE_MD.read_text(encoding="utf-8") == md
        return 0 if fresh else 1
    OUT.write_text(text, encoding="utf-8")
    CLAUDE_MD.write_text(md, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} and {CLAUDE_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
